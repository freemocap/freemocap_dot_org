// Builds freemocap.org/go/<slug> short links and their QR codes from links.csv.
//
//   cd go && npm install   (once)
//   node build.mjs
//
// Writes:
//   ../httpdocs/dist/go/.htaccess   the redirects (deploys with the site)
//   qr/<slug>.svg, qr/<slug>.png    print-ready QR codes for each link

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const BASE = "https://freemocap.org/go/";
const here = dirname(fileURLToPath(import.meta.url));
const htaccessPath = join(here, "..", "httpdocs", "dist", "go", ".htaccess");
const qrDir = join(here, "qr");

// Each row is slug,url,note. The note is free text and may contain commas.
const rows = readFileSync(join(here, "links.csv"), "utf8")
  .split(/\r?\n/)
  .slice(1)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"));

const links = [];
const seen = new Set();
for (const line of rows) {
  const [slug, url] = line.split(",").map((s) => s.trim());
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) {
    throw new Error(`Bad slug "${slug}": use lowercase letters, numbers, and dashes only.`);
  }
  // https only: an http:// destination would show phones a "not secure" warning.
  if (!/^https:\/\/\S+$/.test(url ?? "")) {
    throw new Error(`Bad url for "${slug}": "${url}" (must start with https://)`);
  }
  if (seen.has(slug)) throw new Error(`Duplicate slug "${slug}"`);
  seen.add(slug);
  links.push({ slug, url });
}

// Apache treats $ and % in a rewrite target as backreferences, so escape them.
const escapeTarget = (url) => url.replace(/([$%])/g, "\\$1");

const htaccess = [
  "# GENERATED by go/build.mjs from go/links.csv. Do not edit by hand.",
  "# 302 (temporary) on purpose so browsers never cache a link and we can repoint it later.",
  "",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  "",
  ...links.map(({ slug, url }) => `RewriteRule ^${slug}/?$ ${escapeTarget(url)} [NC,NE,L,R=302]`),
  "",
  "# Unknown or mistyped codes land on the homepage instead of a 404.",
  "RewriteRule ^ https://freemocap.org/ [L,R=302]",
  "</IfModule>",
  "",
].join("\n");

mkdirSync(dirname(htaccessPath), { recursive: true });
writeFileSync(htaccessPath, htaccess);

// Regenerate QR codes from scratch so removed links don't leave stale images.
rmSync(qrDir, { recursive: true, force: true });
mkdirSync(qrDir, { recursive: true });
const opts = { errorCorrectionLevel: "M", margin: 4 };
for (const { slug } of links) {
  const target = BASE + slug;
  writeFileSync(join(qrDir, `${slug}.svg`), await QRCode.toString(target, { ...opts, type: "svg" }));
  await QRCode.toFile(join(qrDir, `${slug}.png`), target, { ...opts, width: 1200 });
}

console.log(`${links.length} link(s) -> ${htaccessPath}`);
for (const { slug, url } of links) console.log(`  ${BASE}${slug}  ->  ${url}`);
console.log(`QR codes in ${qrDir}: ${readdirSync(qrDir).join(", ")}`);
