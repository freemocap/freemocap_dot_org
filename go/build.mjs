// Builds freemocap.org/go/<slug> short links and their QR codes from links.csv.
//
//   cd go && npm install   (once)
//   node build.mjs
//
// Writes:
//   ../httpdocs/dist/go/.htaccess   the redirects (deploys with the site)
//   qr/<slug>.svg, qr/<slug>.png    print-ready QR codes for each link

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";
import sharp from "sharp";

const BASE = "https://freemocap.org/go/";
const here = dirname(fileURLToPath(import.meta.url));
const htaccessPath = join(here, "..", "httpdocs", "dist", "go", ".htaccess");
const qrDir = join(here, "qr");

// Each row is slug,url,note. The note is free text and may contain commas.
const rows = readFileSync(join(here, "links.csv"), "utf8")
  .split(/\r?\n/)
  .slice(1)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"));

const links = [];
const seen = new Set();
for (const line of rows) {
  const [slug, url] = line.split(",").map((s) => s.trim());
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) {
    throw new Error(`Bad slug "${slug}": use lowercase letters, numbers, and dashes only.`);
  }
  // https only: an http:// destination would show phones a "not secure" warning.
  if (!/^https:\/\/\S+$/.test(url ?? "")) {
    throw new Error(`Bad url for "${slug}": "${url}" (must start with https://)`);
  }
  if (seen.has(slug)) throw new Error(`Duplicate slug "${slug}"`);
  seen.add(slug);
  links.push({ slug, url });
}

// Apache treats $ and % in a rewrite target as backreferences, so escape them.
const escapeTarget = (url) => url.replace(/([$%])/g, "\\$1");

const htaccess = [
  "# GENERATED by go/build.mjs from go/links.csv. Do not edit by hand.",
  "# 302 (temporary) on purpose so browsers never cache a link and we can repoint it later.",
  "",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  "",
  ...links.map(({ slug, url }) => `RewriteRule ^${slug}/?$ ${escapeTarget(url)} [NC,NE,L,R=302]`),
  "",
  "# Unknown or mistyped codes land on the homepage instead of a 404.",
  "RewriteRule ^ https://freemocap.org/ [L,R=302]",
  "</IfModule>",
  "",
].join("\n");

mkdirSync(dirname(htaccessPath), { recursive: true });
writeFileSync(htaccessPath, htaccess);

// QR codes: black modules, white circle in the middle with the b&w skelly logo.
// Error correction H tolerates ~30% damage; the circle covers well under that.
const MARGIN = 4; // quiet zone in modules; scanners need it
const CIRCLE = 0.26; // circle diameter as a fraction of the code (without margin)
const LOGO = 0.72; // logo height as a fraction of the circle
const LABEL_GAP = 2; // modules between the code and the top of the link text
const LABEL_FONT = "Helvetica, Arial, sans-serif";
const logoPng = readFileSync(join(here, "logo-bw.png"));
const logoMeta = await sharp(logoPng).metadata();
const logoHref = `data:image/png;base64,${logoPng.toString("base64")}`;

async function qrSvg(text, label) {
  const { modules } = QRCode.create(text, { errorCorrectionLevel: "H" });
  const n = modules.size;
  const total = n + MARGIN * 2;
  const c = total / 2;
  const r = (n * CIRCLE) / 2;
  let path = "";
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (!modules.get(y, x)) continue;
      // Skip modules that touch the circle so its edge stays clean.
      const dx = Math.max(Math.abs(x + MARGIN + 0.5 - c) - 0.5, 0);
      const dy = Math.max(Math.abs(y + MARGIN + 0.5 - c) - 0.5, 0);
      if (Math.hypot(dx, dy) < r) continue;
      path += `M${x + MARGIN} ${y + MARGIN}h1v1h-1z`;
    }
  }
  const lh = r * 2 * LOGO;
  const lw = (lh * logoMeta.width) / logoMeta.height;
  // The destination URL under the code, scaled so its ink spans exactly the code's width.
  const m = await measureText(label);
  const font = (MEASURE_SIZE * n) / m.width;
  const k = font / MEASURE_SIZE;
  const inkTop = n + MARGIN + LABEL_GAP;
  const x = MARGIN - m.left * k;
  const y = inkTop - m.top * k;
  const h = inkTop + m.height * k + MARGIN / 2;
  return {
    height: h / total,
    svg: [
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${h}" shape-rendering="crispEdges">`,
      `<rect width="${total}" height="${h}" fill="#fff"/>`,
      `<path d="${path}" fill="#000"/>`,
      `<image href="${logoHref}" x="${c - lw / 2}" y="${c - lh / 2}" width="${lw}" height="${lh}" shape-rendering="auto"/>`,
      `<text x="${x}" y="${y}" font-family="${LABEL_FONT}" font-size="${font}" fill="#000" shape-rendering="auto">${xml(label)}</text>`,
      `</svg>`,
    ].join(""),
  };
}

// Measure the label's ink box (not its advance width) as the PNG renderer draws it,
// with the baseline at y=0 and the text origin at x=0.
const MEASURE_SIZE = 200;
async function measureText(label) {
  const W = MEASURE_SIZE * label.length;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${MEASURE_SIZE * 2}"><rect width="100%" height="100%" fill="#fff"/><text x="${MEASURE_SIZE}" y="${MEASURE_SIZE * 1.5}" font-family="${LABEL_FONT}" font-size="${MEASURE_SIZE}" fill="#000">${xml(label)}</text></svg>`;
  const { info } = await sharp(Buffer.from(svg)).trim({ threshold: 128 }).toBuffer({ resolveWithObject: true });
  return {
    left: -info.trimOffsetLeft - MEASURE_SIZE,
    top: -info.trimOffsetTop - MEASURE_SIZE * 1.5,
    width: info.width,
    height: info.height,
  };
}

function xml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// Regenerate QR codes from scratch so removed links don't leave stale images.
rmSync(qrDir, { recursive: true, force: true });
mkdirSync(qrDir, { recursive: true });
for (const { slug, url } of links) {
  // Print exactly where the code ends up, minus https:// and a bare trailing slash.
  const label = url.replace(/^https:\/\//, "").replace(/^([^/]+)\/$/, "$1");
  const { svg, height } = await qrSvg(BASE + slug, label);
  writeFileSync(join(qrDir, `${slug}.svg`), svg);
  await sharp(Buffer.from(svg), { density: 1200 })
    .resize(1200, Math.round(1200 * height))
    .png()
    .toFile(join(qrDir, `${slug}.png`));
}

console.log(`${links.length} link(s) -> ${htaccessPath}`);
for (const { slug, url } of links) console.log(`  ${BASE}${slug}  ->  ${url}`);
console.log(`QR codes in ${qrDir}: ${readdirSync(qrDir).join(", ")}`);
